#!/usr/bin/env python3
"""
questlog.py - build the Pip-Boy quest log (data\\quests.txt) from mod/quests.txt.

    python tools/questlog.py            # print the generated quests.txt
    python tools/questlog.py --check    # only report problems

The engine reads data\\quests.txt (pipboy.cc): one line per entry,

    location, description, gvar, display_threshold, completed_threshold

where location is a map.msg line (the area name, 1500 + area) and description
a quests.msg line. FOC writes the map file and the GVAR name instead, so
neither number has to be kept in step by hand: the area comes from
worldmap.area_groups (the same numbering deploy writes into city.txt) and the
GVAR from mod/ids/gvars.txt. deploy.py writes the result; the text lives in
mod/data/text/english/game/quests.msg and is copied as it is.

FOC ships only its own entries. The base's quests.txt is all vanilla quests on
vanilla variables, which nothing in FOC should ever show.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import worldmap  # noqa: E402
from foclib import GameIndex  # noqa: E402
from gen_ids import read_registry  # noqa: E402
from ids import FOC_START  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "mod" / "quests.txt"
QUESTS_MSG = ROOT / "mod" / "data" / "text" / "english" / "game" / "quests.msg"
GVARS = ROOT / "mod" / "ids" / "gvars.txt"
QUESTS_VFS = "data\\quests.txt"

MSG_LINE = re.compile(r"^\{(\d+)\}\{[^}]*\}\{", re.M)


class QuestLogError(Exception):
    pass


def read_source(path: Path = SOURCE) -> list[tuple[int, str, int, str, int, int]]:
    """[(source line no, map file, msg id, gvar name, shown at, done at)]"""
    out = []
    for n, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        s = raw.split("#", 1)[0].strip()
        if not s:
            continue
        parts = [p.strip() for p in s.split(",")]
        if len(parts) != 5:
            raise QuestLogError(f"{path.name}:{n}: expected 5 fields, got {len(parts)}")
        try:
            out.append((n, parts[0], int(parts[1]), parts[2], int(parts[3]), int(parts[4])))
        except ValueError:
            raise QuestLogError(f"{path.name}:{n}: line, shown at and done at must be numbers")
    return out


def gvar_numbers() -> dict[str, int]:
    return {name: FOC_START["gvar"] + i for i, name in enumerate(read_registry(GVARS)) if name}


def map_areas(gi: GameIndex) -> dict[str, int]:
    """map file name (upper case) -> worldmap area id"""
    area0 = worldmap.base_area_count(gi)
    out = {}
    for i, (_, members) in enumerate(worldmap.area_groups(worldmap.read_maps_registry())):
        for rec in members:
            out[rec["filename"].upper()] = area0 + i
    return out


def build(gi: GameIndex) -> tuple[str, list[str]]:
    """(quests.txt text, problems)"""
    problems = []
    rows = read_source()
    gvars = gvar_numbers()
    areas = map_areas(gi)
    msg_ids = (set(int(m) for m in MSG_LINE.findall(QUESTS_MSG.read_text(encoding="cp1252")))
               if QUESTS_MSG.is_file() else set())
    lines = ["# quests.txt - generated by tools/questlog.py from mod/quests.txt. Do not edit.",
             "# location (map.msg), description (quests.msg), gvar, display, completed"]
    for n, mapname, msg, gname, shown, done in rows:
        where = f"quests.txt:{n}"
        area = areas.get(mapname.upper())
        if area is None:
            problems.append(f"{where}: {mapname} is not a map in mod/ids/maps.txt")
        if gname not in gvars:
            problems.append(f"{where}: {gname} is not in mod/ids/gvars.txt")
        if msg not in msg_ids:
            problems.append(f"{where}: quests.msg has no line {{{msg}}}")
        if not 0 < shown < done:
            problems.append(f"{where}: needs 0 < shown at ({shown}) < done at ({done})")
        if area is not None and gname in gvars:
            lines.append(f"{1500 + area}, {msg}, {gvars[gname]}, {shown}, {done}")
    return "\r\n".join(lines) + "\r\n", problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text, problems = build(GameIndex())
    for p in problems:
        print(f"ERROR: {p}")
    if not args.check:
        print(text, end="")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
