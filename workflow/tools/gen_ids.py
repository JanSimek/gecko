#!/usr/bin/env python3
"""
gen_ids.py - turn mod/ids/*.txt into the generated header scripts_src/foc/foc_ids.h.

    python tools/gen_ids.py [--check]

`--check` regenerates in memory and fails if the file on disk is stale, so the
build can refuse to compile against an out-of-date header.

The header is generated, never hand-edited. Edit mod/ids/*.txt instead.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from ids import FOC_START, PROTO_KEY  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
IDS = ROOT / "mod" / "ids"
HEADER = ROOT / "scripts_src" / "foc" / "foc_ids.h"

TYPE_CODE = {  # PID high byte per object type
    "proto_items": 0, "proto_critters": 1, "proto_scenery": 2,
    "proto_walls": 3, "proto_tiles": 4, "proto_misc": 5,
}
TYPE_TAG = {  # in a PID_FOC_ name whose index another type already uses
    "proto_items": "ITEM", "proto_critters": "CRIT", "proto_scenery": "SCEN",
    "proto_walls": "WALL", "proto_tiles": "TILE", "proto_misc": "MISC",
}


def read_registry(path: Path) -> list[str]:
    """
    One entry per line, in allocation order.

    '#' comment lines do NOT consume an index. Blank lines DO - they are retired
    slots, and keeping them is what stops later IDs from shifting.
    """
    if not path.is_file():
        return []
    out = []
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        s = raw.strip()
        if s.startswith("#"):
            continue
        out.append(s)
    # trailing blanks are just file whitespace, not retired slots
    while out and out[-1] == "":
        out.pop()
    return out


def sym(name: str) -> str:
    """Turn a filename into a C identifier fragment: focstart.int -> FOCSTART."""
    return re.sub(r"[^A-Za-z0-9_]", "_", Path(name).stem).upper()


def generate() -> str:
    L: list[str] = []
    add = L.append

    add("/*  GENERATED by tools/gen_ids.py - do not edit.")
    add("    Source of truth is the mod/ids registry. Run gen_ids.py after editing it.")
    add("")
    add("    Fallout 2 IDs are positional: a script index is a 1-based line in")
    add("    scripts.lst, a proto index is a 1-based line in its type .lst, and a")
    add("    GVAR number is a line position in vault13.gam. These constants are")
    add("    those absolute numbers.  */")
    add("")
    add("#ifndef FOC_IDS_H")
    add("#define FOC_IDS_H")
    add("")

    # --- scripts
    entries = read_registry(IDS / "scripts.txt")
    start = FOC_START["script"]
    add(f"// scripts.lst lines {start}..{start + max(0, len(entries) - 1)}")
    for i, name in enumerate(entries):
        if not name:
            add(f"// (retired slot {start + i})")
            continue
        add(f"#define SCRIPT_{sym(name):<28} ({start + i})")
    if not entries:
        add("// (none allocated yet)")
    add("")

    # --- gvars
    entries = read_registry(IDS / "gvars.txt")
    start = FOC_START["gvar"]
    add(f"// vault13.gam slots {start}..{start + max(0, len(entries) - 1)}")
    for i, name in enumerate(entries):
        if not name:
            add(f"// (retired slot {start + i})")
            continue
        add(f"#define {name:<36} ({start + i})")
    if not entries:
        add("// (none allocated yet)")
    add("")

    # --- protos
    # Items, critters and the rest share index numbers (item 706 and critter
    # 706 are different protos), so a bare PID_FOC_00000706 would be defined
    # once per type and the compiler would keep the last: PID_SCRAP_METAL
    # once made "Jack" the critter. The first type to use a name keeps it;
    # a later one gets its type in the name (PID_FOC_CRIT_00000706).
    seen: set[str] = set()
    for key, code in TYPE_CODE.items():
        entries = read_registry(IDS / f"{key}.txt")
        if not entries:
            continue
        start = FOC_START[key]
        add(f"// {key}: .lst lines {start}..{start + len(entries) - 1}")
        for i, name in enumerate(entries):
            if not name:
                add(f"// (retired slot {start + i})")
                continue
            idx = start + i
            pid = (code << 24) | idx
            label = sym(name)
            # a bare 00000700.pro gives a useless symbol; let the registry
            # supply "00000700.pro  NAME" to name it properly
            if label in seen:
                label = f"{TYPE_TAG[key]}_{label}"
            seen.add(label)
            add(f"#define PID_FOC_{label:<24} ({pid})   // 0x{pid:08X}, index {idx}")
        add("")

    # --- maps (mod/ids/maps.txt is keyed by explicit id, not positional)
    from worldmap import area_groups, base_area_count, read_maps_registry
    maps = read_maps_registry(IDS / "maps.txt")
    if maps:
        add("// maps.txt sections - cur_map_index / load_map values")
        for rec in maps:
            add(f"#define MAP_FOC_{sym(rec['filename']):<24} ({rec['id']})")
        add("")
        # worldmap areas: one per map that owns an area, numbered after the
        # base's city.txt in registry order (worldmap.py assigns them the same way)
        from foclib import GameIndex
        area0 = base_area_count(GameIndex())
        add("// city.txt areas - mark_area_known / cur_town values")
        for i, (owner, _members) in enumerate(area_groups(maps)):
            add(f"#define AREA_FOC_{sym(owner['filename']):<23} ({area0 + i})")
        add("")

    add("#endif  // FOC_IDS_H")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    text = generate()
    HEADER.parent.mkdir(parents=True, exist_ok=True)

    if args.check:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            print(f"STALE: {HEADER.relative_to(ROOT)} does not match mod/ids/*.txt")
            print("       run: python tools/gen_ids.py")
            return 1
        print(f"{HEADER.relative_to(ROOT)} is up to date")
        return 0

    HEADER.write_text(text, encoding="utf-8")
    n = len([l for l in text.splitlines() if l.startswith("#define")])
    print(f"wrote {HEADER.relative_to(ROOT)}  ({n} defines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
